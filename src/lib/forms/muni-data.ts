export const REGIONS = REGION_GROUPS.flatMap((group) => group.regions);

const REGIONS_SET = new Set(REGIONS);

const EMAIL_RE = /^[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Za-z]{2,}$/;

function digitsOnly(value: string): string {
  return (value || "").replace(/\D/g, "");
}

export function validEmail(value: string): boolean {
  const s = (value || "").trim();
  if (!s || s.length > 254 || s.includes("..")) return false;
  return EMAIL_RE.test(s);
}

export function validSnils(value: string): boolean {
  const digits = digitsOnly(value);
  if (digits.length !== 11) return false;
  if (digits === "00000000000") return false;
  const number = Number(digits.slice(0, 9));
  if (number < 1001998) return true;
  const checksum = Array.from(digits.slice(0, 9)).reduce(
    (sum, ch, i) => sum + Number(ch) * (9 - i),
    0,
  );
  let check: number;
  if (checksum < 100) check = checksum;
  else if (checksum === 100 || checksum === 101) check = 0;
  else {
    check = checksum % 101;
    if (check === 100) check = 0;
  }
  return check === Number(digits.slice(9, 11));
}

function innControl(digits: string, coeffs: number[]): string {
  const total = coeffs.reduce((sum, coeff, i) => sum + Number(digits[i]) * coeff, 0);
  return String((total % 11) % 10);
}

export function validInn(value: string): boolean {
  const digits = digitsOnly(value);
  if (digits.length !== 12 || new Set(digits).size === 1) return false;
  const n11 = innControl(digits, [7, 2, 4, 10, 3, 5, 9, 4, 6, 8]);
  const n12 = innControl(digits, [3, 7, 2, 4, 10, 3, 5, 9, 4, 6, 8]);
  return n11 === digits[10] && n12 === digits[11];
}

export function normalizeDistrict(value: string): string {
  const s = (value || "").replace(/\s+/g, " ").trim();
  return DISTRICT_ALIASES[s] ?? s;
}

export function validRegion(value: string): boolean {
  return REGIONS_SET.has((value || "").trim());
}
